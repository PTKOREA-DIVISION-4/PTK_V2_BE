#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
SOURCE_ENV="${SOURCE_ENV:-$ROOT_DIR/.env}"
OUT_FILE="$SCRIPT_DIR/.env.server"

if [ ! -f "$SOURCE_ENV" ]; then
  echo "로컬 .env 파일을 찾을 수 없습니다: $SOURCE_ENV" >&2
  exit 1
fi

umask 077

python3 - "$SOURCE_ENV" "$OUT_FILE" <<'PY'
import os
import secrets
import sys
from pathlib import Path

source_path = Path(sys.argv[1])
out_path = Path(sys.argv[2])

def parse_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, val = line.split("=", 1)
        key = key.strip()
        val = val.strip()
        if len(val) >= 2 and ((val[0] == '"' and val[-1] == '"') or (val[0] == "'" and val[-1] == "'")):
            val = val[1:-1]
        values[key] = val
    return values

src = parse_env(source_path)
existing = parse_env(out_path)

mysql_password = existing.get("MYSQL_PASSWORD") or secrets.token_hex(24)
mysql_root_password = existing.get("MYSQL_ROOT_PASSWORD") or secrets.token_hex(24)

ncp_key_id = (
    src.get("X_NCP_APIGW_API_KEY_ID")
    or src.get("X-NCP-APIGW-API-KEY-ID")
    or src.get("NCP_APIGW_API_KEY_ID")
    or ""
)
ncp_key = (
    src.get("X_NCP_APIGW_API_KEY")
    or src.get("X-NCP-APIGW-API-KEY")
    or src.get("NCP_APIGW_API_KEY")
    or ""
)

passthrough_defaults = [
    ("APP_NAME", "PTKOREA Factbook API"),
    ("API_V1_PREFIX", "/api/v1"),
    ("PERPLEXITY_API_KEY", ""),
    ("ANTHROPIC_API_KEY", ""),
    ("SCRAPECREATORS_API_KEY", ""),
    ("APIFY_API_TOKEN", ""),
    ("PERPLEXITY_BASE_URL", "https://api.perplexity.ai"),
    ("PERPLEXITY_MODEL", "sonar-pro"),
    ("ANTHROPIC_BASE_URL", "https://api.anthropic.com"),
    ("ANTHROPIC_MODEL", "claude-sonnet-5-5"),
    ("SCRAPECREATORS_BASE_URL", "https://api.scrapecreators.com"),
    ("APIFY_BASE_URL", "https://api.apify.com/v2"),
    ("NAVER_APIGW_BASE_URL", "https://naverapihub.apigw.ntruss.com"),
    ("DEFAULT_NAVER_SHOPPING_CATEGORY_ID", "50000002"),
    ("CACHE_TTL_SECONDS", "86400"),
    ("HTTP_TIMEOUT_SECONDS", "45.0"),
    ("MAX_CONCURRENT_PERPLEXITY", "3"),
    ("MAX_CONCURRENT_NAVER", "5"),
    ("MAX_CONCURRENT_SCRAPECREATORS", "4"),
    ("MAX_CONCURRENT_APIFY", "3"),
    ("MAX_CONCURRENT_ANTHROPIC", "3"),
]

lines: list[str] = [
    "# Generated by deploy/make-env.sh — DO NOT COMMIT",
    "APP_ENV=production",
    "DEBUG=false",
    "DB_AUTO_CREATE_TABLES=true",
    "STORAGE_ROOT=/app/storage",
    'CORS_ORIGINS=["https://division4.madp.cloud","http://localhost:3000","http://127.0.0.1:3000"]',
    r"CORS_ORIGIN_REGEX=^https://[a-zA-Z0-9-]+\.vercel\.app$",
    f"MYSQL_PASSWORD={mysql_password}",
    f"MYSQL_ROOT_PASSWORD={mysql_root_password}",
    f"X_NCP_APIGW_API_KEY_ID={ncp_key_id}",
    f"X_NCP_APIGW_API_KEY={ncp_key}",
]

written_keys = [
    "APP_ENV",
    "DEBUG",
    "DB_AUTO_CREATE_TABLES",
    "STORAGE_ROOT",
    "CORS_ORIGINS",
    "CORS_ORIGIN_REGEX",
    "MYSQL_PASSWORD",
    "MYSQL_ROOT_PASSWORD",
    "X_NCP_APIGW_API_KEY_ID",
    "X_NCP_APIGW_API_KEY",
]

for key, default in passthrough_defaults:
    val = src.get(key, default)
    lines.append(f"{key}={val}")
    written_keys.append(key)

out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
os.chmod(out_path, 0o600)

print("생성된 서버 env 키 목록 (값 미출력):")
for key in written_keys:
    print(f" - {key}")
PY

if [ $# -ge 1 ]; then
  HOST="$1"
  ${SSH:-ssh} "$HOST" 'mkdir -p /opt/ptk-v2 && umask 077 && cat > /opt/ptk-v2/.env && chmod 600 /opt/ptk-v2/.env' < "$OUT_FILE"
  echo "원격 서버($HOST:/opt/ptk-v2/.env)에 안전하게 설치 완료 (권한 600)."
fi
